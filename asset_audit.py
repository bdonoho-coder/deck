"""Asset audit for a public release: which files we may ship, which we must replace.

Writes research/asset-audit.md. Rules come from research/monetization-report.md:
  LineX icons (linex-src)        personal use, never publish  -> replace (Simple Icons, CC0)
  niivu folder packs (icons/*)   all rights reserved          -> replace (our own HUD folder packs)
  Simple Icons (appicons/src)    CC0                           -> ok
  Google Fonts (fonts/src)       OFL, no reserved names       -> ok, ship OFL text
  Omarchy colors (omarchy-dl)    MIT                           -> ok, credit; wallpapers: check each
  our generators' output         ours                          -> ok

  py -P asset_audit.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent
sys.path.insert(0, str(ROOT))
from make_app_icons import APPS, LINEX_ICONS, THEMES  # noqa: E402

# Folder packs under icons/<theme>/: our generator writes "HUD Folders"; anything else is a downloaded pack.
OWN_PACK = "HUD Folders"
NIIVU = {"Nord Papirus", "Gruvbox", "Papirus Deep Orange", "Tokyo Night blank"}


def pack_of(theme):
    folders = [p.name for p in (ROOT / "icons" / theme).iterdir() if p.is_dir()]
    others = [f for f in folders if f not in (OWN_PACK, "files")]
    if OWN_PACK in folders:
        # The picker prefers our pack; leftover downloaded packs must still stay out of a release.
        note = f" (also present, exclude from release: {', '.join(others)})" if others else ""
        return OWN_PACK + note, "ours", "ok"
    name = others[0] if others else "(none)"
    return name, "niivu (all rights reserved)" if name in NIIVU else "unknown", "REPLACE"


def wallpapers_of(theme):
    src = ROOT / "omarchy-dl" / theme
    if theme.startswith("hud-"):
        return "hud_wallpaper.py (ours)", "ok"
    if theme == "amber-lab":
        return "fal-generated (ours)", "ok"
    files = [p.name for p in src.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".webp")] if src.exists() else []
    # Our generators write 7-ridges, 8-contours (theme_wallpaper.py) and 9-glow (make_themes.py).
    own = [n for n in ("7-ridges.jpg", "8-contours.jpg", "9-glow.jpg") if (ROOT / "wallpapers" / theme / n).exists()]
    if own:
        return (f"ours: {', '.join(own)}; omarchy-dl photos ({', '.join(files) or 'none'}) stay local, "
                "exclude from release"), "ok"
    return f"omarchy-dl/{theme}: {', '.join(files) or '(none)'} (third-party photos/art from the Omarchy repo)", "CHECK each"


def main():
    lines = ["# Asset audit for release", "",
             "Generated by asset_audit.py. REPLACE = cannot ship; CHECK = license unknown per file; ok = ship with credit.", ""]

    lines += ["## App icons (appicons/<set>/*.ico)", "", "| Set | Apps | From LineX (REPLACE) | From Simple Icons / letters (ok) |", "|---|---|---|---|"]
    linex_apps = sorted(a for a in APPS if a in LINEX_ICONS)
    for theme in THEMES:
        sets = [theme, theme + "-color"] if theme.startswith("hud-") else [theme]
        for s in sets:
            if not (ROOT / "appicons" / s).exists():
                continue
            if theme.startswith("hud-"):
                lines.append(f"| {s} | {len(APPS)} | {len(linex_apps)}: {', '.join(linex_apps)} | {len(APPS) - len(linex_apps)} |")
            else:
                lines.append(f"| {s} | {len(APPS)} | 0 | {len(APPS)} |")
    lines += ["", f"Fix: `py -P make_app_icons.py --release` writes release/appicons/ with no LineX logos (Simple Icons filled logos or letters for all {len(linex_apps)} apps).", ""]

    lines += ["## Folder icon packs (icons/<theme>/)", "", "| Theme | Pack | Source | Verdict |", "|---|---|---|---|"]
    bad = []
    for theme in THEMES:
        pack, src, verdict = pack_of(theme)
        if verdict != "ok":
            bad.append(theme)
        lines.append(f"| {theme} | {pack} | {src} | {verdict} |")
    if bad:
        lines += ["", f"Fix: build HUD-style folder packs in each theme's colors with make_folder_icons.py for: {', '.join(bad)}.", ""]
    else:
        lines += ["", "All packs are ours (make_folder_icons.py builds every theme in omarchy-dl).", ""]

    lines += ["## Wallpapers", "", "| Theme | Source | Verdict |", "|---|---|---|"]
    for theme in THEMES:
        src, verdict = wallpapers_of(theme)
        lines.append(f"| {theme} | {src} | {verdict} |")
    lines += ["", "Release packaging: copy only the 'ours' wallpapers (7-, 8-, 9-*.jpg) and the HUD Folders packs; leave omarchy-dl photos and downloaded icon packs out.", ""]

    fonts = sorted(p.name for p in (ROOT / "fonts" / "src").glob("*")) if (ROOT / "fonts" / "src").exists() else []
    lines += ["## Fonts (fonts/src -> fonts/hud, family renamed to HUD Face)", "",
              "OFL 1.1, no Reserved Font Names: ok to bundle; ship OFL.txt and the original copyright lines; do not sell the fonts alone.", "",
              *[f"- {f}" for f in fonts], ""]

    lines += ["## Names and credits", "",
              "- Rename the Files fork (name, logo, package identity) before any release; keep LICENSE-MIT, LICENSE-MPL, NOTICE.md.",
              "- Do not use Omarchy, Nord, Catppuccin, Gruvbox, Tokyo Night, Everforest as product names; credit them (MIT / Apache-2.0 for Tokyo Night: add NOTICE).",
              "- Simple Icons are CC0 but the brand marks belong to their owners: no brand logos in marketing or the product icon.", ""]

    out = ROOT / "research" / "asset-audit.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    print(f"LineX apps per HUD set: {len(linex_apps)}; packs to replace: {len(bad)}")


if __name__ == "__main__":
    main()
